"""v1.8.0c — FEXP2_32 polynomial-coefficient generator (pinned deliverable).

Degree-6 minimax fit for 2^f on [0,1) with c0 CONSTRAINED to exactly 1.0
(belt-and-suspenders with the FP_CLASSIFY integer bypass: P(0) == 1 makes
the poly path agree bit-exactly with the bypass at f == 0).

Fit: constrained Remez exchange in pure numpy (float64). The target
g(f) = 2^f - 1 is approximated from span{f..f^6} (6-dimensional Haar
system on (0,1]), so the best error equioscillates at 7 points; the
7x7 exchange system solves c1..c6 plus the level h. float64 is ample:
the equioscillation level is ~2.9e-9 >> 1e-16 solver noise.

Quantization (documented internal fixed point): coefficients are RNE-
quantized to Q1.30 (31-bit unsigned, value = coeff * 2^-30 — the "~30
bit" width of the winning design); the Horner micro-loop runs in Q2.30
with round-to-odd products (see scripts/golden_fp32.py fexp2_micro).

Emits two COMMITTED artifacts:

  include/generated/fp_fexp2_coeffs.vh    FP_FEXP2_C0..C6 localparams
  include/generated/fp_fexp2_coeffs.json  exact integers (golden model)

Deterministic: fixed node initialization, fixed iteration cap, no
timestamps. Modes: generate (default) / --check (byte-diff freshness,
same contract as scripts/gen_isa_tables.py).
"""

import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
GEN = REPO / "include" / "generated"

ARTIFACTS = {
    "vh":   GEN / "fp_fexp2_coeffs.vh",
    "json": GEN / "fp_fexp2_coeffs.json",
}

SPDX_VH = (
    "// SPDX-License-Identifier: SHL-2.1 OR CERN-OHL-W-2.0\n"
    "// SPDX-FileCopyrightText: 2026 윤병익 (BYUNG-IK YEUN) and WaveTensor contributors\n"
)

DEGREE = 6
SCALE_BITS = 30
GRID_N = 400001
MAX_ITERS = 60


def _poly_err(c, grid, g):
    p = np.zeros_like(grid)
    for i in range(DEGREE, 0, -1):
        p = (p + c[i - 1]) * grid
    return p - g


def remez_fit():
    """Return (c[6] float64 for f^1..f^6, max_abs_err) with c0 == 1 implied."""
    j = np.arange(1, DEGREE + 2)
    t = 0.5 * (1.0 - np.cos(np.pi * j / (DEGREE + 1)))
    grid = np.linspace(0.0, 1.0, GRID_N)
    g = np.exp2(grid) - 1.0

    c = np.zeros(DEGREE)
    for _ in range(MAX_ITERS):
        A = np.empty((DEGREE + 1, DEGREE + 1))
        for i in range(1, DEGREE + 1):
            A[:, i - 1] = t ** i
        A[:, DEGREE] = (-1.0) ** np.arange(DEGREE + 1)
        sol = np.linalg.solve(A, np.exp2(t) - 1.0)
        c = sol[:DEGREE]
        err = _poly_err(c, grid, g)
        # alternating extrema: argmax |err| inside each sign-constant segment
        s = np.sign(err)
        s[s == 0] = 1.0
        segs = np.split(np.arange(GRID_N), np.nonzero(np.diff(s))[0] + 1)
        cand = [seg[np.argmax(np.abs(err[seg]))] for seg in segs]
        if len(cand) > DEGREE + 1:
            cand = sorted(cand, key=lambda k: -abs(err[k]))[:DEGREE + 1]
            cand.sort()
        if len(cand) < DEGREE + 1:
            break
        tn = grid[cand]
        if np.allclose(tn, t, rtol=0.0, atol=1e-12):
            break
        t = tn
    return c, float(np.max(np.abs(_poly_err(c, grid, g))))


def quantize(c):
    q = [1 << SCALE_BITS]
    for ci in c:
        qi = int(np.rint(ci * (1 << SCALE_BITS)))     # np.rint is RNE
        assert 0 < qi < (1 << 31), qi                 # Q1.30 unsigned
        q.append(qi)
    return q


def _hdr_vh(self_sha):
    return (SPDX_VH +
            "// GENERATED by scripts/gen_fexp2_coeffs.py\n"
            f"// generator sha256={self_sha} — DO NOT EDIT (edit the script, regenerate, commit both)\n")


def emit_vh(q, fit_err, self_sha):
    lines = [_hdr_vh(self_sha)]
    lines.append("// v1.8.0c FEXP2_32 degree-6 minimax coefficients for 2^f, f in [0,1).")
    lines.append("// Q1.30 unsigned (value = C * 2^-30); C0 pinned to exactly 1.0.")
    lines.append(f"// Real-coefficient fit max |err| ~ {fit_err:.3e} (~0.024 ulp of [1,2)).")
    lines.append("// Horner order C6..C0 in Q2.30 with round-to-odd products —")
    lines.append("// golden-model twin: include/generated/fp_fexp2_coeffs.json.")
    for i, qi in enumerate(q):
        lines.append(f"    localparam [30:0] FP_FEXP2_C{i} = 31'd{qi};")
    return "\n".join(lines) + "\n"


def emit_json(q, fit_err, self_sha):
    payload = {
        "_doc": "v1.8.0c FEXP2_32 degree-6 minimax coefficients — exact integers "
                "shared by RTL (fp_fexp2_coeffs.vh) and the golden model "
                "(scripts/golden_fp32.py). coeffs_q30[i] is the f^i coefficient.",
        "_generator": "scripts/gen_fexp2_coeffs.py",
        "_generator_sha256": self_sha,
        "degree": DEGREE,
        "scale_bits": SCALE_BITS,
        "domain": "[0,1)",
        "c0_exact_one": True,
        "fit_max_abs_err": float(f"{fit_err:.6e}"),
        "coeffs_q30": q,
    }
    return json.dumps(payload, indent=1) + "\n"


def render_all():
    self_sha = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    c, fit_err = remez_fit()
    q = quantize(c)
    return {
        "vh":   emit_vh(q, fit_err, self_sha),
        "json": emit_json(q, fit_err, self_sha),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="regenerate and byte-diff against committed artifacts")
    args = ap.parse_args()

    rendered = render_all()
    if args.check:
        stale = []
        for key, content in rendered.items():
            path = ARTIFACTS[key]
            existing = path.read_text() if path.exists() else ""
            if existing != content:
                diff = "".join(difflib.unified_diff(
                    existing.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=str(path), tofile=f"{path} (regenerated)"))
                stale.append((path, diff))
        if stale:
            for path, diff in stale:
                print(f"STALE: {path}", file=sys.stderr)
                print(diff, file=sys.stderr)
            return 1
        print("gen_fexp2_coeffs: OK — all generated artifacts fresh.")
        return 0

    for key, content in rendered.items():
        path = ARTIFACTS[key]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
