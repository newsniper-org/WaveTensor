"""v1.8.0c — FRSQRT32 / FDIV seed-ROM generator (pinned deliverable).

Emits four COMMITTED artifacts:

  include/generated/fp_frsqrt_seed_rom.vh   256 x 9-bit rsqrt seed ROM
  include/generated/fp_frsqrt_seed_rom.json exact integer entries (golden model)
  include/generated/fp_fdiv_seed_rom.vh     256 x 9-bit reciprocal seed ROM
  include/generated/fp_fdiv_seed_rom.json   exact integer entries (golden model)

The .json sidecars are consumed by scripts/golden_fp32.py, so RTL and the
golden model provably share the exact same tables (the release-gate sweeps
run against these shipped artifacts, not reference reconstructions).

FRSQRT32 ROM: index {exp_field[0], mant[22:16]} (8 bits). exp_field[0] is
the fp32 BIASED exponent LSB: biased-LSB==1 <=> unbiased exponent even
<=> x' in [1,2); biased-LSB==0 <=> x' in [2,4). Entry = 9-bit RNE
quantization of rsqrt(midpoint-of-segment), y0 = entry * 2^-9. Entries
land in [256, 511] — rsqrt over [1,4) is (0.5, 1).

FDIV ROM: index mant[22:15] of b (8 bits), b' in [1,2). Entry = 9-bit RNE
of 1/midpoint, y0 = entry * 2^-9. Entries land in [256, 511].

RNE ties break to even via exact integer comparison (no floating point
anywhere). Deterministic: no timestamps; the sha256 of THIS script is
embedded so a reader can verify which generator produced an artifact.

Modes: generate (default) writes in place; --check regenerates and
byte-diffs against the committed files (exit 0 fresh / 1 stale), same
contract as scripts/gen_isa_tables.py.
"""

import argparse
import difflib
import hashlib
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GEN = REPO / "include" / "generated"

ARTIFACTS = {
    "frsqrt_vh":   GEN / "fp_frsqrt_seed_rom.vh",
    "frsqrt_json": GEN / "fp_frsqrt_seed_rom.json",
    "fdiv_vh":     GEN / "fp_fdiv_seed_rom.vh",
    "fdiv_json":   GEN / "fp_fdiv_seed_rom.json",
}

SPDX_VH = (
    "// SPDX-License-Identifier: SHL-2.1 OR CERN-OHL-W-2.0\n"
    "// SPDX-FileCopyrightText: 2026 윤병익 (BYUNG-IK YEUN) and WaveTensor contributors\n"
)


def rne_rat(num, den):
    """RNE of num/den (positive ints) to an integer, ties to even."""
    q, r = divmod(num, den)
    if 2 * r > den or (2 * r == den and (q & 1)):
        q += 1
    return q


def rne_sqrt_rat(num, den):
    """RNE of sqrt(num/den) (positive ints) to an integer, ties to even.

    floor via isqrt(num*den)//den, then exact half-point comparison:
    sqrt(num/den) vs n0+1/2  <=>  4*num vs den*(2*n0+1)^2."""
    n0 = math.isqrt(num * den) // den
    lhs, rhs = 4 * num, den * (2 * n0 + 1) ** 2
    if lhs > rhs or (lhs == rhs and (n0 & 1)):
        return n0 + 1
    return n0


def build_frsqrt_rom():
    rom = []
    for i in range(256):
        biased_lsb = (i >> 7) & 1
        m7 = i & 0x7F
        # segment midpoint of x': [1,2) half steps by 1/128, [2,4) doubled
        num, den = 256 + 2 * m7 + 1, 256
        if biased_lsb == 0:
            num *= 2
        # entry = RNE(2^9 / sqrt(num/den)) = RNE(sqrt(2^18 * den / num))
        e = rne_sqrt_rat((1 << 18) * den, num)
        assert 256 <= e <= 511, (i, e)
        rom.append(e)
    return rom


def build_fdiv_rom():
    rom = []
    for m8 in range(256):
        # midpoint b' = (512 + 2*m8 + 1)/512; entry = RNE(2^9 / b')
        e = rne_rat((1 << 9) * 512, 512 + 2 * m8 + 1)
        assert 256 <= e <= 511, (m8, e)
        rom.append(e)
    return rom


def _hdr_vh(self_sha):
    return (SPDX_VH +
            "// GENERATED by scripts/gen_frsqrt_seed_rom.py\n"
            f"// generator sha256={self_sha} — DO NOT EDIT (edit the script, regenerate, commit both)\n")


def emit_vh(name, doc_lines, rom, self_sha):
    packed = 0
    for i, e in enumerate(rom):
        packed |= e << (9 * i)
    lines = [_hdr_vh(self_sha)]
    lines.extend(f"// {d}" for d in doc_lines)
    lines.append(f"    localparam [2303:0] {name} =")
    lines.append(f"        2304'h{packed:0576X};")
    return "\n".join(lines) + "\n"


def emit_json(doc, index_doc, rom, self_sha):
    payload = {
        "_doc": doc,
        "_generator": "scripts/gen_frsqrt_seed_rom.py",
        "_generator_sha256": self_sha,
        "width_bits": 9,
        "depth": 256,
        "index": index_doc,
        "value_scale": "y0 = entry * 2^-9",
        "entries": rom,
    }
    return json.dumps(payload, indent=1) + "\n"


def render_all():
    self_sha = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    frsqrt = build_frsqrt_rom()
    fdiv = build_fdiv_rom()
    return {
        "frsqrt_vh": emit_vh(
            "FP_FRSQRT_SEED_ROM",
            ["v1.8.0c FRSQRT32 seed: 256 x 9-bit, entry i at bits [9*i+8 : 9*i].",
             "Index {exp_field[0], mant[22:16]}: biased-exponent LSB 1 <=> x' in",
             "[1,2), 0 <=> x' in [2,4). y0 = entry * 2^-9 ~ rsqrt(segment midpoint),",
             "9-bit RNE. Golden-model twin: include/generated/fp_frsqrt_seed_rom.json."],
            frsqrt, self_sha),
        "frsqrt_json": emit_json(
            "v1.8.0c FRSQRT32 seed ROM — exact integer entries shared by RTL "
            "(fp_frsqrt_seed_rom.vh) and the golden model (scripts/golden_fp32.py).",
            "{exp_field[0], mant[22:16]} — biased-exponent LSB 1 <=> x' in [1,2), "
            "0 <=> x' in [2,4); mant[22:16] = top 7 mantissa bits",
            frsqrt, self_sha),
        "fdiv_vh": emit_vh(
            "FP_FDIV_SEED_ROM",
            ["v1.8.0c FDIV reciprocal seed: 256 x 9-bit, entry i at bits [9*i+8 : 9*i].",
             "Index mant[22:15] of b, b' in [1,2). y0 = entry * 2^-9 ~ 1/(segment",
             "midpoint), 9-bit RNE. Golden-model twin: fp_fdiv_seed_rom.json."],
            fdiv, self_sha),
        "fdiv_json": emit_json(
            "v1.8.0c FDIV reciprocal seed ROM — exact integer entries shared by RTL "
            "(fp_fdiv_seed_rom.vh) and the golden model (scripts/golden_fp32.py).",
            "mant[22:15] of b (top 8 mantissa bits), b' in [1,2)",
            fdiv, self_sha),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="regenerate and byte-diff against committed artifacts")
    args = ap.parse_args()

    rendered = render_all()
    if args.check:
        stale = []
        for key, content in rendered.items():
            path = ARTIFACTS[key]
            existing = path.read_text() if path.exists() else ""
            if existing != content:
                diff = "".join(difflib.unified_diff(
                    existing.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=str(path), tofile=f"{path} (regenerated)"))
                stale.append((path, diff))
        if stale:
            for path, diff in stale:
                print(f"STALE: {path}", file=sys.stderr)
                print(diff, file=sys.stderr)
            return 1
        print("gen_frsqrt_seed_rom: OK — all generated artifacts fresh.")
        return 0

    for key, content in rendered.items():
        path = ARTIFACTS[key]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
