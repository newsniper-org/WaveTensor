def sby_anchors(path: Path) -> list:
    """`# PROVES: Model.guard` 앵커 목록 — 파일 순서 그대로.

    선언은 **줄머리** `# PROVES:` 다 (산문 속 `` `# PROVES:` `` 인용은 선언이 아니다).
    가드 이름 뒤에 이름 문자가 이어지면(`tag1_x` 의 `tag`) 옛 판은 앞토막만 읽었다 —
    이제 선언인데 문법대로 읽히지 않으면 크게 운다 (2026-09-26 파도 4 검토).
    """
    decl = re.compile(r"^\s*#\s*PROVES:")
    pat = re.compile(rf"^\s*#\s*PROVES:\s*([A-Za-z]+)\.({GUARD_NAME})(?![A-Za-z0-9_])")
    out = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        m = pat.search(line)
        if m:
            out.append(f"{m.group(1)}.{m.group(2)}")
        elif decl.search(line):
            fail(f"{path}:{i} — PROVES 앵커를 읽지 못했다 (형식: # PROVES: <Model>.<guard> …, "
                 f"가드 이름 문법 {GUARD_NAME})")
    return out


def sby_inputs(path: Path) -> list:
    """`[files]` 절이 선언한 입력 경로 — 저장소 루트 기준.

    이 파서가 저장소에서 셋째 사본이다 (sby_impact.py · 아래 경로 실재성
    검사와 같은 문법). 사본을 하나 더 만드는 대신 **sby_sweep.sh 가 이
    함수를 호출한다** — 증거의 입력 목록과 lint 의 대조 목록이 같은 코드에서
    나오지 않으면 두 층이 서로 다른 것을 보게 되고, 그것이 정확히
    notes-vacuity-detection.md 가 이름 붙인 「게이트가 자기가 무엇을 세는지
    모른다」의 형태다.
    """
    out, in_files = [], False
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("["):
            in_files = s.lower().startswith("[files]")
            continue
        if not in_files or not s or s.startswith("#"):
            continue
        out.append(s.split()[-1])  # `dst src` 형태도 허용된다
    return out


def sby_tasks(path: Path):
    """`[tasks]` 절이 선언한 태스크 이름 집합. 절이 없으면 None.

    `sby_inputs` 와 **같은 파일**에 산다 (사본 금지 규율). 증거의 태스크 집합을
    이것으로 재유도하는 것이 「부분 실행」을 잡는 유일한 자리다 — `.sby` 를
    고치면 sby_sha256 이 이미 stale 을 내므로, 겹치지 않는 곳은 「`.sby` 는
    그대로인데 스윕이 태스크 하나를 못 돌렸다」 하나뿐이다.

    2026-08-27 실측: 18개 .sby 전부 `[tasks]` 를 갖는다
    (bmc/prove/cover 13 · bmc/cover 2 · prove/cover 2 · deep/cover 1).
    None 반환은 「선언이 없다」이고, 그때 증거의 태스크 집합을 재유도할 상대가
    없으므로 **게이트의 결함**(UNCOUNTED)으로 흘려보낸다.
    """
    out, in_tasks, seen = set(), False, False
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("["):
            in_tasks = s.lower().startswith("[tasks]")
            seen = seen or in_tasks
            continue
        if not in_tasks or not s or s.startswith("#"):
            continue
        out.add(s.split()[0])
    return out if seen else None


def parse_task_states(s: str):
    """`"bmc:PASS cover:PASS"` -> {태스크: 상태}. 못 쪼개면 None.

    None 은 「상태를 *세지 못했다*」이지 「없었다」가 아니다 — 그 둘을 가르는
    것이 이 저장소가 두 오탐으로 배운 규율이고, 호출자가 UNCOUNTED 로 인쇄한다.
    """
    toks = s.split()
    if not toks:
        return None
    out = {}
    for t in toks:
        m = re.fullmatch(r"([^:\s]+):([^:\s]+)", t)
        if not m:
            return None
        out[m.group(1)] = m.group(2)
    return out


def evidence_cells(doc) -> tuple:
    """(assert 최댓값, cover 최댓값). **유도는 여기 한 곳뿐이다.**

    schema/2 는 `per_task` 에서 유도하고 증거에 최댓값을 따로 적지 않는다.
    두 수(최댓값·태스크별)가 각자 저장되면 3차가 닫은 「같은 사실에 두 기계가
    다른 수를 인쇄한다」(lint_guard_map 77 vs lint_postformal 74)의 재발이다.
    구판(schema/1)은 최댓값만 갖고 있으므로 저장된 `cells` 를 읽는다.
    """
    pt = doc.get("per_task")
    if isinstance(pt, dict) and pt:
        return (max(int(v.get("assert", 0)) for v in pt.values()),
                max(int(v.get("cover", 0)) for v in pt.values()))
    c = doc.get("cells", {})
    return int(c.get("assert", 0)), int(c.get("cover", 0))


